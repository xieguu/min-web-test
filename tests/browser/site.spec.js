import { test, expect } from '@playwright/test';

test('桌面：浏览、账号、发布编辑删除全流程', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const email = `browser-${Date.now()}@example.com`;
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '少一点，刚刚好。' })).toBeVisible();
  await expect(page.locator('.article-card')).toHaveCount(4);
  await page.screenshot({ path: 'test-results/home-desktop.png', fullPage: true });
  await page.getByRole('searchbox', { name: '搜索内容' }).fill('小小的开始');
  await expect(page.locator('.article-card')).toHaveCount(1);
  await page.getByRole('searchbox', { name: '搜索内容' }).fill('不存在的关键词');
  await expect(page.getByRole('heading', { name: '没有找到相关内容' })).toBeVisible();
  await page.getByRole('button', { name: '清除筛选' }).click();
  await expect(page.locator('.article-card')).toHaveCount(4);
  await page.getByRole('button', { name: '使用说明', exact: true }).click();
  await expect(page.locator('.article-card')).toHaveCount(2);
  await page.getByRole('link', { name: '创建账号', exact: true }).click();
  await page.getByRole('textbox', { name: '昵称', exact: true }).fill('浏览器测试');
  await page.getByRole('textbox', { name: '邮箱', exact: true }).fill(email);
  await page.getByLabel('密码', { exact: true }).fill('Browser-test-2026');
  await page.getByRole('button', { name: '显示密码' }).click();
  await expect(page.getByLabel('密码', { exact: true })).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: '创建账号', exact: true }).click();
  await expect(page.getByRole('link', { name: '我的内容', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.getByRole('link', { name: '发布内容', exact: true }).click();
  await page.getByLabel('标题', { exact: true }).fill('浏览器发布测试 <script>');
  await page.getByLabel('正文', { exact: false }).fill('正文第一段\n\n测试 <img src=x onerror=alert(1)> 按纯文本显示。');
  await page.getByRole('button', { name: '发布内容', exact: true }).click();
  await expect(page.getByRole('heading', { name: '浏览器发布测试 <script>' })).toBeVisible();
  await expect(page.locator('.article-body img')).toHaveCount(0);
  const articleUrl = page.url();
  await page.reload();
  await expect(page.getByRole('link', { name: '编辑内容' })).toBeVisible();
  await page.getByRole('link', { name: '编辑内容' }).click();
  await page.getByLabel('标题', { exact: true }).fill('修改后的测试内容');
  await page.getByRole('button', { name: '保存修改' }).click();
  await expect(page.getByRole('heading', { name: '修改后的测试内容' })).toBeVisible();
  await page.screenshot({ path: 'test-results/article-desktop.png', fullPage: true });
  await page.getByRole('link', { name: /我的账号/ }).click();
  await page.getByRole('textbox', { name: '昵称', exact: true }).fill('更新昵称');
  await page.getByRole('button', { name: '保存资料' }).click();
  await expect(page.getByRole('heading', { name: '更新昵称', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '退出登录' }).click();
  await expect(page.getByRole('link', { name: '登录', exact: true })).toBeVisible();
  await page.goto('/write');
  await expect(page).toHaveURL(/\/login\?next=/);
  await page.getByRole('textbox', { name: '邮箱' }).fill(email);
  await page.getByLabel('密码', { exact: true }).fill('incorrect-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('邮箱或密码不正确');
  await page.getByLabel('密码', { exact: true }).fill('Browser-test-2026');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '写下一点新想法。' })).toBeVisible();
  await page.goto(articleUrl);
  await page.getByRole('button', { name: '删除内容', exact: true }).click();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await expect(page.getByRole('heading', { name: '修改后的测试内容' })).toBeVisible();
  await page.getByRole('button', { name: '删除内容', exact: true }).click();
  await page.getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(page.getByRole('heading', { name: '第一篇内容，等你来写。' })).toBeVisible();
  expect(errors).toEqual([]);
});

test('手机：布局、阅读和注册页面', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.locator('.article-card')).toHaveCount(4);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/home-mobile.png', fullPage: true });
  await page.getByRole('link', { name: /从这里开始，少一点复杂/ }).click();
  await expect(page.getByRole('heading', { name: '从这里开始，少一点复杂。' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: '创建账号', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '昵称', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/register-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('/');
  await expect(page.locator('.article-card')).toHaveCount(4);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
